<?php
declare(strict_types=1);

/**
 * Web-based installer — accessible directly as /install.php
 * After successful installation this file renames itself to install.php.done.
 */

require_once __DIR__ . '/src/bootstrap.php';

// Already installed?
if (file_exists(CONFIG_PATH)) {
    http_response_code(403);
    render('install_done');
    exit;
}

$errors = [];
$post   = [];

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    // CSRF guard
    if (!csrf_verify()) {
        $errors[] = __('install.err_csrf');
    } else {
        $post = [
            'db_host'   => trim($_POST['db_host']  ?? ''),
            'db_name'   => trim($_POST['db_name']  ?? ''),
            'db_user'   => trim($_POST['db_user']  ?? ''),
            'db_pass'   => $_POST['db_pass']        ?? '',
            'admin_email' => trim($_POST['admin_email'] ?? ''),
        ];

        $adminPassword        = $_POST['admin_password']         ?? '';
        $adminPasswordConfirm = $_POST['admin_password_confirm'] ?? '';

        // Validation
        if (empty($post['db_host']))  $errors[] = __('install.err_db_host');
        if (empty($post['db_name']))  $errors[] = __('install.err_db_name');
        if (empty($post['db_user']))  $errors[] = __('install.err_db_user');

        if (empty($post['admin_email']) || !filter_var($post['admin_email'], FILTER_VALIDATE_EMAIL)) {
            $errors[] = __('install.err_admin_email');
        }
        if (strlen($adminPassword) < 8) {
            $errors[] = __('validation.password_min_8');
        }
        if ($adminPassword !== $adminPasswordConfirm) {
            $errors[] = __('validation.password_mismatch');
        }

        // Test DB connection
        $pdo = null;
        if (empty($errors)) {
            try {
                $dsn = sprintf(
                    'mysql:host=%s;dbname=%s;charset=utf8mb4',
                    $post['db_host'],
                    $post['db_name']
                );
                $pdo = new PDO($dsn, $post['db_user'], $post['db_pass'], [
                    PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
                    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                ]);
            } catch (PDOException $e) {
                $errors[] = __('install.err_db_connect', ['error' => $e->getMessage()]);
            }
        }

        // Run the base schema. 001_initial.sql is kept up to date with the
        // current schema (users/multi-account tables included) — it's only
        // ever used here, for a brand-new install. Existing installations
        // upgrade via the numbered migration files instead (see UPGRADE.md).
        if (empty($errors) && $pdo !== null) {
            try {
                $sql = file_get_contents(BASE_DIR . '/migrations/001_initial.sql');
                foreach (split_sql_statements($sql) as $stmt) {
                    $pdo->exec($stmt);
                }
                // 001 already contains migrations 001-003: record them, then
                // apply anything newer (004+) the same way the admin button does.
                $migrator = new Migrator($pdo);
                $migrator->markBaselineApplied();
                $migrator->run();
            } catch (Throwable $e) {
                $errors[] = __('install.err_schema', ['error' => $e->getMessage()]);
            }
        }

        // Create SuperAdmin account
        if (empty($errors) && $pdo !== null) {
            try {
                $hash = password_hash($adminPassword, PASSWORD_BCRYPT, ['cost' => 12]);
                $pdo->prepare(
                    "INSERT INTO users (email, password_hash, role, status) VALUES (?, ?, 'superadmin', 'active')"
                )->execute([
                    $post['admin_email'],
                    $hash,
                ]);
            } catch (PDOException $e) {
                $errors[] = __('install.err_admin_create', ['error' => $e->getMessage()]);
            }
        }

        // Generate and write config.php
        if (empty($errors)) {
            $scheme   = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
            $host     = $_SERVER['HTTP_HOST'] ?? 'localhost';
            // Include subdirectory if the app lives in one (e.g. /mitbringliste)
            $script   = $_SERVER['SCRIPT_NAME'] ?? '';
            $basePath = ($script !== '') ? rtrim(dirname($script), '/\\') : '';
            $appUrl   = $scheme . '://' . $host . $basePath;
            $secret   = bin2hex(random_bytes(32)); // 64-char hex

            $configContent = '<?php' . PHP_EOL
                . '// Generated by Mitbringliste installer — ' . date('Y-m-d H:i:s') . PHP_EOL
                . '// DO NOT COMMIT THIS FILE TO VERSION CONTROL' . PHP_EOL . PHP_EOL
                . '$config = [' . PHP_EOL
                . "    'db_host'    => " . var_export($post['db_host'], true) . ',' . PHP_EOL
                . "    'db_name'    => " . var_export($post['db_name'], true) . ',' . PHP_EOL
                . "    'db_user'    => " . var_export($post['db_user'], true) . ',' . PHP_EOL
                . "    'db_pass'    => " . var_export($post['db_pass'], true) . ',' . PHP_EOL
                . "    'app_url'    => " . var_export($appUrl, true) . ',' . PHP_EOL
                . "    'app_secret' => " . var_export($secret, true) . ',' . PHP_EOL
                . '];' . PHP_EOL;

            if (file_put_contents(CONFIG_PATH, $configContent) === false) {
                $errors[] = __('install.err_config_write');
            }
        }

        // Success: remove install.php
        if (empty($errors)) {
            // Try delete first, rename as fallback — both are non-critical since
            // config.php existing already blocks re-installation.
            if (!@unlink(__FILE__)) {
                @rename(__FILE__, __FILE__ . '.done');
            }

            flash('success', __('install.done_success'));
            redirect(base_url('admin/login'));
        }
    }
}

// Render — layout.php handles null $db gracefully
$pageTitle = __('install.title');
render('install', ['errors' => $errors, 'post' => $post]);
